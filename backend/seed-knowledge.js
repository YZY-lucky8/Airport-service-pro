async function seedKnowledge() {
  console.log('📚 开始导入知识库种子数据...');

  // 连接数据库
  const pool = await dbAdapter.connect();
  console.log('  数据库已连接 (' + dbAdapter.getMode() + ')');

  // 清空旧数据
  await pool.execute('DELETE FROM knowledge_base');
  console.log('  已清空旧数据');

  let inserted = 0;
  for (const item of data) {
    try {
      await pool.execute(
        'INSERT INTO knowledge_base (title, content, category, keywords, priority, is_active) VALUES (?, ?, ?, ?, ?, 1)',
        item
      );
      inserted++;
    } catch (err) {
      console.error('  插入失败: ' + item[0], err.message);
    }
  }

  console.log('✅ 成功导入 ' + inserted + '/' + data.length + ' 条知识库记录');

  // 验证
  const [count] = await pool.query('SELECT COUNT(*) as total FROM knowledge_base WHERE is_active = 1');
  console.log('📊 当前知识库有效记录总数: ' + count[0].total);

  // 分类统计
  const cats = await pool.query('SELECT category, COUNT(*) as cnt FROM knowledge_base WHERE is_active = 1 GROUP BY category');
  console.log('\n📂 分类统计:');
  for (const c of cats) {
    console.log('   ' + c.category + ': ' + c.cnt + ' 条');
  }

  process.exit(0);
}

seedKnowledge().catch(err => {
  console.error('❌ 种子数据导入失败:', err);
  process.exit(1);
});
